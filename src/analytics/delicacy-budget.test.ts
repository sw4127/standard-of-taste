/**
 * E6/S7 — WHAT TEN MINUTES OF THE DELICACY TRIALS BUYS [SIMULATED].
 *
 * The sharper half of E6. The scored count of 15 was chosen on 2026-08-08 as
 * "analysable without a session nobody finishes" — an ROI judgment made before
 * the rate framing existed — while Spearman-Brown put alpha 0.70 near 42
 * trials. Those two numbers have never been reconciled, and the session has
 * been shipping at 15 ever since.
 *
 * TWO CRITERIA, BECAUSE THE INSTRUMENT SERVES TWO MASTERS. I expected them to
 * want different session lengths and wrote that down before measuring. They do
 * not. They converge on the same answer from opposite directions, which is a
 * better result than the one I predicted:
 *
 *   INDIVIDUAL — `delicacyVerdict` places a person in a tier from
 *     above = (nCorrect - n/2) / (n/2). That is what one human reads. The gate
 *     is how often the tier is the RIGHT tier, exactly as E6/S6 gated the
 *     Prestige verdict against its own +/-15% lines.
 *
 *   COHORT — alpha and split-half reliability decide whether the response set
 *     can carry item analysis, IRT and the Lab at all. That is where the 42
 *     came from. It is a property of the MATRIX, not of any person, and no
 *     individual's result gets better or worse because of it.
 *
 * The 42-trial figure answers the cohort question. It was never an answer to
 * the individual one, and the session length was set as if it were.
 *
 * ================================ THE ANSWER ================================
 *
 * AT THE SHIPPING LENGTH THE VERDICT IS WRONG ALMOST HALF THE TIME. Fifteen
 * scored trials place a person in the right tier 57.5% of the time on the
 * synthetic bank and 54.2% on the live pool. The Prestige Test, measured the
 * same way in E6/S6, manages 89.3%.
 *
 * THE CAUSE IS RESOLUTION, NOT LENGTH PER SE. At 15 trials the SD of a person's
 * measured share-correct is 0.106, while the narrowest shipped tier is 0.125
 * wide — a band 1.18 SD across. The ruler is nearly as wide as the thing it is
 * measuring. Six tiers on the chance-to-perfect range need about six times 2 SD
 * of room; 15 trials supply enough for about two.
 *
 * BOTH CRITERIA LAND ON ~42-45 TRIALS, BY DIFFERENT ROUTES. Cohort reliability
 * crosses alpha 0.70 at 42 (reproducing the 2026-08-08 Spearman-Brown figure
 * from a fresh simulation), and the narrowest tier crosses 2 SD at about 45.
 * Two unrelated arguments arriving at the same number is the strongest thing in
 * this slice.
 *
 * AND 42 TRIALS IS 21 MINUTES — which is exactly the session nobody finishes
 * that 15 was chosen to avoid. So the honest options are not "15 or 42". They
 * are: buy the resolution with minutes, or STOP PRINTING RESOLUTION THAT IS NOT
 * THERE and say less at 15. The second is free, and it is the one the measured
 * numbers support.
 *
 * See `docs/analytics/e6-delicacy.txt`, regenerated by this test.
 *
 * ITEMS BEYOND THE LIVE POOL ARE SYNTHETIC AND SAID SO (N3). Only 18 pairs
 * exist — 3 practice, 15 scored — so every length past 15 is a claim about a
 * pool we would have to author, not about the one we ship. The curve is
 * therefore run entirely on the synthetic bank, so that every point is
 * comparable to every other; the live pool's own point is reported separately
 * and labelled.
 *
 * EVERYTHING HERE IS SIMULATED (N3). Zero real responses.
 */

