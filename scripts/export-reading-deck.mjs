/**
 * EXPORT THE READING'S COPY (blueprint Part 7; BA-6, BA-9).
 *
 * The fifth deck: every sentence the blueprint build added — the front door's
 * new lines, the shared nav, the reading page, every line the three
 * illustrative listeners render, the reading's on-surface statement, and the
 * Company view. GENERATED, like the other four, because a hand-typed list is a
 * selection and starts rotting the moment a string moves.
 *
 * THE BLUEPRINT STATEMENTS ARE PRINTED AND LOCKED. /reading, /company and
 * /learn/why render them from `docs/blueprint.md`. A writer should see them,
 * because they are on the page, and must not rewrite them here: they change
 * only in that file, by owner ruling (BA-1), and `blueprint.test.ts` holds
 * every copy to it.
 *
 * NOT YET THROUGH A WRITING PASS: none of this copy has been.
 *
 *   node scripts/export-reading-deck.mjs > docs/copy-deck-reading.md
 */
import { execSync } from "node:child_process";
import { writeFileSync, unlinkSync } from "node:fs";

const script = `
import { it } from "vitest";
import * as landing from "@/content/landing";
import * as readingCopy from "@/content/reading/copy";
import * as companyCopy from "@/content/company/copy";
import { ASSUMPTIONS } from "@/content/company/plan";
import { SITE_NAV } from "@/content/site-nav";
import { READING_STATEMENT } from "@/content/reading/statement";
import { LISTENERS } from "@/content/reading/listeners";
import { readingFor } from "@/content/reading/reading";
import { NEITHER } from "@/content/reading/lines";
import { BP_STATEMENTS } from "@/content/blueprint";

const strings = (mod) => Object.entries(mod).filter(([, v]) => typeof v === "string");

it("exports", () => {
  const out = {
    landing: [
      ["LANDING_HEADLINE", landing.LANDING_HEADLINE],
      ["LANDING_READING_TURN", landing.LANDING_READING_TURN],
      ["LANDING_CARDS_LEAD", landing.LANDING_CARDS_LEAD],
      ["HEARING_KICKER", landing.HEARING_KICKER],
      ["HEARING_HEADING", landing.HEARING_HEADING],
    ],
    nav: SITE_NAV.map((l) => [l.href, l.label]),
    reading: [...strings(readingCopy), ["NEITHER", NEITHER], ["READING_STATEMENT", READING_STATEMENT]],
    lines: LISTENERS.map((l) => ({
      name: l.name,
      lines: readingFor(l).lines.map((x) => ({
        kind: x.kind,
        pattern: x.pattern,
        receipt: x.receipt,
        offers: x.offers.map((o) => [o.question, o.words.join(", ")]),
        cue: x.cue.label + ": " + x.cue.text,
      })),
      // The prompt's sound words per flaw family (BP-BRIDGE), authored in listeners.ts.
      families: l.clusters.map((c) => [c.id, c.family.tuning, c.family.timing, c.family.compression]),
    })),
    company: strings(companyCopy).filter(([k]) => k !== "HOST_NAME"),
    companyLists: {
      FIT_LINES: companyCopy.FIT_LINES,
      KILL_LINES: companyCopy.KILL_LINES,
      metrics: [companyCopy.NORTH_STAR, ...companyCopy.SUPPORTING, ...companyCopy.GUARDRAILS],
      stakeholders: companyCopy.STAKEHOLDERS,
      assumptions: ASSUMPTIONS.map((a) => [a.label, a.shown, a.reason]),
    },
    blueprint: BP_STATEMENTS.map((s) => [s.id, s.text]),
  };
  console.log("DECK_START" + JSON.stringify(out) + "DECK_END");
});
`;

const tmp = "src/content/reading/__export.test.ts";
writeFileSync(tmp, script, "utf8");
let raw = "";
try {
  raw = execSync(`npx vitest run ${tmp} --reporter=verbose`, { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
} finally {
  unlinkSync(tmp);
}
const m = /DECK_START([\s\S]*?)DECK_END/.exec(raw);
if (!m) {
  console.error(raw.slice(-4000));
  throw new Error("export-reading-deck: produced no deck");
}
const d = JSON.parse(m[1]);

const L = [];
const w = (s = "") => L.push(s);
const quote = (s) => w("> " + s);

w("# Copy deck — the reading, the front door and the Company view");
w();
w("Generated by `node scripts/export-reading-deck.mjs`. Do not edit this file; edit the content modules named under each section.");
w("**None of this copy has been through a writing pass.**");
w();

w("## 1. The front door — `src/content/landing.ts`");
w();
for (const [name, text] of d.landing) {
  w(`*\`${name}\`:*`);
  w();
  quote(text);
  w();
}

w("## 2. The shared navigation — `src/content/site-nav.ts`");
w();
// One line: a label alone is too short to carry a sentence id (deck-templates.test.ts).
w(`*In order, as every page's header shows them: ${d.nav.map(([href]) => "\`" + href + "\`").join(", ")}*`);
w();
quote(d.nav.map(([, label]) => label).join(" · "));
w();

w("## 3. The reading page — `src/content/reading/copy.ts`, `statement.ts`");
w();
w("*`READING_STATEMENT` is derived from CLAUDE.md by a test: change it in the constitution's third-surface amendment, not here.*");
w();
for (const [name, text] of d.reading) {
  w(`*\`${name}\`:*`);
  w();
  quote(text);
  w();
}

w("## 4. The lines the three listeners render — `src/content/reading/lines.ts`");
w();
w("*These are renderings: the numbers and track names are filled in from the plays. Edit the template in `lines.ts`; a line's pattern names no feeling and its offers are questions (BA-3, `register.ts`).*");
w();
for (const l of d.lines) {
  w(`### ${l.name}`);
  w();
  for (const x of l.lines) {
    w(`*${x.kind}:*`);
    w();
    quote(x.pattern);
    w();
    quote(x.receipt);
    w();
    for (const [q, words] of x.offers) {
      quote(q);
      w();
      w(`*prompt words: ${words}*`);
      w();
    }
    quote(x.cue);
    w();
  }
  // Unquoted on purpose: quoted lines take positional ids, and these are all under the id floor.
  w("*The prompt's sound words, by family (`listeners.ts`; the bridge marks each group against a Threshold sitting):*");
  w();
  for (const [id, tuning, timing, fidelity] of l.families) {
    w("- `" + id + "` · Tuning: " + tuning + " · Timing: " + timing + " · Fidelity: " + fidelity);
  }
  w();
}

w("## 5. The Company view — `src/content/company/copy.ts`, `plan.ts`");
w();
for (const [name, text] of d.company) {
  w(`*\`${name}\`:*`);
  w();
  quote(text);
  w();
}
for (const line of [...d.companyLists.FIT_LINES, ...d.companyLists.KILL_LINES]) {
  quote(line);
  w();
}
for (const mt of d.companyLists.metrics) {
  quote(mt.name);
  w();
  quote(mt.definition);
  w();
  quote(mt.why);
  w();
}
for (const s of d.companyLists.stakeholders) {
  quote(s.team);
  w();
  quote(s.question);
  w();
  quote(s.answer);
  w();
}
for (const [label, shown, reason] of d.companyLists.assumptions) {
  quote(label + ": " + shown);
  w();
  quote(reason);
  w();
}

w("## 6. LOCKED — the blueprint statements the pages render — `docs/blueprint.md`");
w();
w("*Printed so a writer sees what is on the page. Not editable here or in any component: they change only in `docs/blueprint.md`, by owner ruling (BA-1).*");
w();
for (const [id, text] of d.blueprint) {
  w(`*${id}:*`);
  w();
  quote(text);
  w();
}

process.stdout.write(L.join(String.fromCharCode(10)) + String.fromCharCode(10));
